/** Translate only known managed content; project-owned text is user data. */
export function translateManagedDashboardText(
  text: string,
  owner: "PROJECT" | "LANGFUSE",
  t: TFunction,
): string {
  return owner === "LANGFUSE" && MANAGED_DASHBOARD_TEXT.has(text)
    ? t(text)
    : text;
}
